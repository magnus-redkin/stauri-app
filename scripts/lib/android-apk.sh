#!/usr/bin/env bash
# android-apk.sh — step for building the signed APK (split out of release.sh).
# Sourced from release.sh and release-android.sh.
# Expects: $ROOT, $VERSION. Sets APK_PATH.

# ---------- 7a. APK (Android, release, signed) ----------
echo
if [[ "${RELEASE_SKIP_ANDROID:-0}" == "1" ]]; then
  echo "[7a] Android APK: пропущен (RELEASE_SKIP_ANDROID=1, собирает release-android.sh)"
else
echo "[7a] Android APK (release)"

ANDROID_DIR="$ROOT/src-tauri/gen/android"
if [[ ! -d "$ANDROID_DIR" ]]; then
  echo "ERROR: нет $ANDROID_DIR — выполните 'cargo tauri android init'." >&2
  exit 1
fi

# Signing: the keystore lives outside the repository, the password in the
# keyring (same pattern as Tauri's).
KS_PATH="${STAURI_ANDROID_KEYSTORE:-$HOME/.android/stauri-release.jks}"
if [[ ! -f "$KS_PATH" ]]; then
  echo "ERROR: keystore не найден: $KS_PATH" >&2
  exit 1
fi
if [[ -z "${STAURI_ANDROID_KEYSTORE_PASSWORD:-}" ]] && command -v secret-tool >/dev/null 2>&1; then
  STAURI_ANDROID_KEYSTORE_PASSWORD="$(secret-tool lookup service stauri-app key android-keystore-password 2>/dev/null || true)"
fi
if [[ -z "${STAURI_ANDROID_KEYSTORE_PASSWORD:-}" ]]; then
  echo "ERROR: пароль android-keystore не найден в keyring." >&2
  exit 1
fi
export STAURI_ANDROID_KEYSTORE="$KS_PATH"
export STAURI_ANDROID_KEYSTORE_PASSWORD

# versionCode follows the Tauri CLI formula (tauri-cli mobile/android/mod.rs):
# major*1000000 + minor*1000 + patch, so 0.4.0 becomes 4000. Matching Tauri
# matters: it rewrites tauri.properties on every build, and this number must be
# the one it would write. A prerelease and the final 0.4.0 share the same code,
# so promoting a beta to a release does not change it either.
VC="$(python3 -c "
import re, sys
m = re.match(r'(\d+)\.(\d+)\.(\d+)', '$VERSION')
print(int(m[1])*1000000 + int(m[2])*1000 + int(m[3]))
")"
cat > "$ANDROID_DIR/app/tauri.properties" <<PROPS
// THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
tauri.android.versionName=$VERSION
tauri.android.versionCode=$VC
PROPS
echo "  versionName=$VERSION versionCode=$VC"

# Build through Tauri: the same rust binary as for the AppImage, plus the signed APK.
pnpm tauri android build --apk --target aarch64 2>&1 | sed 's/^/  /'

APK_SRC="$ANDROID_DIR/app/build/outputs/apk/universal/release/app-universal-release.apk"

# Signing does not live in the generated project. `tauri android init` recreates
# `src-tauri/gen/android/` without a signingConfigs block, so after any
# regeneration Gradle builds an *unsigned* APK and the release step would stop
# here. Signing the artefact ourselves keeps the release independent of the
# generated project and of whatever Gradle happened to inherit.
find_apksigner() {
  command -v apksigner || ls -d "${ANDROID_HOME:-$HOME/Android/sdk}"/build-tools/*/apksigner 2>/dev/null | sort -V | tail -1
}
if [[ ! -f "$APK_SRC" ]]; then
  UNSIGNED="$ANDROID_DIR/app/build/outputs/apk/universal/release/app-universal-release-unsigned.apk"
  if [[ -f "$UNSIGNED" ]]; then
    APKSIGNER="$(find_apksigner)"
    if [[ -z "$APKSIGNER" ]]; then
      echo "ERROR: APK собран без подписи, а apksigner не найден" >&2
      exit 1
    fi
    echo "  подпись: $UNSIGNED → $(basename "$APK_SRC")"
    "$APKSIGNER" sign \
      --ks "$KS_PATH" \
      --ks-key-alias "${STAURI_ANDROID_KEY_ALIAS:-stauri}" \
      --ks-pass env:STAURI_ANDROID_KEYSTORE_PASSWORD \
      --key-pass env:STAURI_ANDROID_KEYSTORE_PASSWORD \
      --out "$APK_SRC" \
      "$UNSIGNED"
  fi
fi
if [[ ! -f "$APK_SRC" ]]; then
  echo "ERROR: APK не собран: $APK_SRC" >&2
  exit 1
fi
APK_PATH="$ROOT/src-tauri/target/release/bundle/apk/Stauri_${VERSION}_aarch64.apk"
mkdir -p "$(dirname "$APK_PATH")"
cp "$APK_SRC" "$APK_PATH"
echo "  apk: $(basename "$APK_PATH")"

# Signature check: the APK must be signed with our key, not the debug key.
APKSIGNER="$(find_apksigner)"
if [[ -n "$APKSIGNER" ]]; then
  "$APKSIGNER" verify --print-certs "$APK_PATH" >/dev/null 2>&1 && echo "  ✓ подпись APK проверена" || {
    echo "ERROR: подпись APK не проходит apksigner verify" >&2
    exit 1
  }
else
  echo "  WARNING: apksigner не найден — подпись APK не проверена" >&2
fi

fi

