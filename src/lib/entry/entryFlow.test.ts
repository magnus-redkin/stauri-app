import { describe, it, expect } from 'vitest';
import {
  credentialNetwork,
  initialPhase,
  isMissingPinError,
  phaseAfterPinLookup,
  pinCreationProblem,
  pinOpenProblem,
  parseNetwork,
  pairingMethods,
  type EntryContext,
  type ProfileSummary,
} from './entryFlow';

const PROFILE: ProfileSummary = { keyUid: '0x9f63…', name: 'Magnus' };
/** Prefix of a real key uid, long enough for the tests that only compare identity. */
const KEY = '0x9f6358c5d1a9bcb5f135c71f800d22dee5e84cd094c269ac8111d492a4f538a8';

function ctx(overrides: Partial<EntryContext> = {}): EntryContext {
  return {
    network: 'mainnet',
    profiles: [],
    canStorePin: true,
    ...overrides,
  };
}

describe('initialPhase', () => {
  it('на чистом устройстве показывает вход, а не PIN', () => {
    // Asking for a PIN before any profile exists is a dead end: there is nothing to
    // unlock, and a user who has never created a profile would read it as a bug.
    expect(initialPhase(ctx())).toEqual({ kind: 'login' });
  });

  it('при наличии профилей показывает экран входа со списком', () => {
    // The list lives on the entry screen, not behind a separate routing step: one screen
    // answers "which profile", and a device with one profile is one tap away from its pad.
    expect(initialPhase(ctx({ profiles: [PROFILE] }))).toEqual({ kind: 'login' });
  });

  it('не спрашивает PIN до выбора профиля', () => {
    // A PIN belongs to a profile; asking before the choice would apply it to whichever
    // profile happens to be first in the list.
    const phase = initialPhase(ctx({ profiles: [PROFILE, { keyUid: KEY }] }));
    expect(phase.kind).toBe('login');
  });
});

describe('phaseAfterPinLookup', () => {
  it('профиль с PIN ведёт на экран ввода PIN', () => {
    expect(phaseAfterPinLookup(PROFILE, 'ready', true)).toEqual({
      kind: 'enter-pin',
      profile: PROFILE,
    });
  });

  it('профиль без PIN оставляет вход по паролю', () => {
    // A profile created before this scheme: the password field still works, and forcing a
    // PIN screen would make it unopenable. It stays on the profile's own screen rather
    // than going back to the start, so the choice does not have to be made twice.
    expect(phaseAfterPinLookup(PROFILE, 'missing', true)).toEqual({
      kind: 'password',
      profile: PROFILE,
    });
  });

  it('после лимита попыток ведёт к фразе, а не к клавиатуре', () => {
    // The envelope will not open any more; a keypad would be a screen that cannot succeed.
    expect(phaseAfterPinLookup(PROFILE, 'locked-out', true)).toEqual({
      kind: 'restore-phrase',
    });
  });

  it('испорченный конверт тоже ведёт к фразе', () => {
    // The password behind a damaged envelope was generated by the application, so the
    // password prompt cannot open it either: the phrase is the only way back, and the
    // keypad would be a screen that cannot succeed.
    expect(phaseAfterPinLookup(PROFILE, 'damaged', true)).toEqual({
      kind: 'restore-phrase',
    });
  });

  it('без поддержки PIN в сборке показывает пароль этого профиля', () => {
    expect(phaseAfterPinLookup(PROFILE, 'ready', false)).toEqual({
      kind: 'password',
      profile: PROFILE,
    });
  });
});

describe('pinOpenProblem', () => {
  it('принимает всё, что могло быть сохранено', () => {
    // Opening is deliberately loose: a stored PIN must stay typeable, or the profile
    // would be locked behind a rule its owner cannot see.
    expect(pinOpenProblem('1379', 12)).toBeNull();
    expect(pinOpenProblem('a', 64)).toBeNull();
    expect(pinOpenProblem('Tr0ub4dor&3!', 64)).toBeNull();
  });

  it('отвергает пустое поле и переполнение', () => {
    expect(pinOpenProblem('', 12)).toBe('Enter your PIN');
    expect(pinOpenProblem('1234567890123', 12)).toBe('The PIN is too long');
  });
});

describe('pinCreationProblem', () => {
  const phone = { creation_min: 5, max_length: 12, digits_only: true, require_classes: false };
  const desktop = { creation_min: 8, max_length: 64, digits_only: false, require_classes: true };

  it('на телефоне требует пять цифр и отвергает очевидные', () => {
    expect(pinCreationProblem('58291', phone)).toBeNull();
    expect(pinCreationProblem('5829', phone)).toBe('The PIN is too short');
    expect(pinCreationProblem('5829a', phone)).toBe('The PIN must be digits');
    expect(pinCreationProblem('12345', phone)).toBe('The PIN is too easy to guess');
    expect(pinCreationProblem('55555', phone)).toBe('The PIN is too easy to guess');
  });

  it('на ноутбуке требует все четыре класса', () => {
    expect(pinCreationProblem('Tr0ub4dor&3', desktop)).toBeNull();
    expect(pinCreationProblem('a1b2c3d4', desktop)).toBe(
      'The PIN must mix lowercase, uppercase, digits and symbols'
    );
    expect(pinCreationProblem('aB1!cD', desktop)).toBe('The PIN is too short');
  });
});

describe('parseNetwork', () => {
  it('принимает обе известные сети', () => {
    expect(parseNetwork('mainnet')).toBe('mainnet');
    expect(parseNetwork('testnet')).toBe('testnet');
  });

  it('отвергает постороннее значение', () => {
    // The value becomes part of a filesystem path on the Rust side.
    expect(parseNetwork('../../etc')).toBeNull();
    expect(parseNetwork('')).toBeNull();
  });
});

describe('credentialNetwork', () => {
  it('сводит любую тестовую сеть к слоту testnet', () => {
    // The picker names presets (`sepolia`, `holesky`); a PIN envelope has two slots.
    expect(credentialNetwork('sepolia')).toBe('testnet');
    expect(credentialNetwork('holesky')).toBe('testnet');
    expect(credentialNetwork('testnet')).toBe('testnet');
  });

  it('оставляет mainnet как есть', () => {
    expect(credentialNetwork('mainnet')).toBe('mainnet');
  });

  it('не путает имя preface со слотом', () => {
    // The bug this guards: the picker's name was turned into `testnet` and passed to
    // `start_backend`, which only knows `mainnet`/`sepolia`/`holesky` and refused it —
    // the selection then snapped back to Mainnet.
    expect(credentialNetwork('sepolia')).not.toBe('sepolia');
  });
});

describe('isMissingPinError', () => {
  it('узнаёт сообщение Rust про отсутствующий конверт', () => {
    expect(isMissingPinError('no PIN is set for this profile')).toBe(true);
    expect(isMissingPinError('no PIN is set for this profile (backend)')).toBe(true);
  });

  it('не путает с другими ошибками PIN', () => {
    expect(isMissingPinError('too many wrong PINs: restore the profile from its seed phrase')).toBe(false);
    expect(isMissingPinError('wrong PIN: 3 attempts left')).toBe(false);
    expect(isMissingPinError('')).toBe(false);
  });
});

describe('pairingMethods', () => {
  it('предлагает Wi-Fi и USB, QR пока выключен', () => {
    const methods = pairingMethods();
    expect(methods.find((m) => m.id === 'wifi')?.enabled).toBe(true);
    expect(methods.find((m) => m.id === 'usb')?.enabled).toBe(true);
    // `qr` has no implementation; it stays visible because the camera permission exists
    // for it, and a disabled row is honest about that.
    expect(methods.find((m) => m.id === 'qr')?.enabled).toBe(false);
  });
});
