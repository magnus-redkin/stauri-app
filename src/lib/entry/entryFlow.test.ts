import { describe, it, expect } from 'vitest';
import {
  initialPhase,
  phaseAfterPinLookup,
  pinProblem,
  parseNetwork,
  pairingMethods,
  type EntryContext,
  type ProfileSummary,
} from './entryFlow';

const PROFILE: ProfileSummary = { keyUid: '0x9f63…', name: 'Magnus' };
/** Prefix of a real key uid, long enough for the tests that only compare identity. */
const KEY = '0x9f6358c5d1a9bcb5f135c71f800d22dee5e84cd094c269ac8111d492a4f538a8';

function ctx(overrides: Partial<EntryContext> = {}): EntryContext {
  return {
    network: 'mainnet',
    profiles: [],
    canStorePin: true,
    ...overrides,
  };
}

describe('initialPhase', () => {
  it('на чистом устройстве показывает вход, а не PIN', () => {
    // Asking for a PIN before any profile exists is a dead end: there is nothing to
    // unlock, and a user who has never created a profile would read it as a bug.
    expect(initialPhase(ctx())).toEqual({ kind: 'login' });
  });

  it('при наличии профилей показывает их список', () => {
    expect(initialPhase(ctx({ profiles: [PROFILE] }))).toEqual({ kind: 'pick-profile' });
  });

  it('не спрашивает PIN до выбора профиля', () => {
    // A PIN belongs to a profile; asking before the choice would apply it to whichever
    // profile happens to be first in the list.
    const phase = initialPhase(ctx({ profiles: [PROFILE, { keyUid: KEY }] }));
    expect(phase.kind).toBe('pick-profile');
  });
});

describe('phaseAfterPinLookup', () => {
  it('профиль с PIN ведёт на экран ввода PIN', () => {
    expect(phaseAfterPinLookup(PROFILE, 'ready', true)).toEqual({
      kind: 'enter-pin',
      profile: PROFILE,
    });
  });

  it('профиль без PIN оставляет вход по паролю', () => {
    // A profile created before this scheme: the password field still works, and forcing a
    // PIN screen would make it unopenable. It stays on the profile's own screen rather
    // than going back to the start, so the choice does not have to be made twice.
    expect(phaseAfterPinLookup(PROFILE, 'missing', true)).toEqual({
      kind: 'password',
      profile: PROFILE,
    });
  });

  it('после лимита попыток ведёт к фразе, а не к клавиатуре', () => {
    // The envelope will not open any more; a keypad would be a screen that cannot succeed.
    expect(phaseAfterPinLookup(PROFILE, 'locked-out', true)).toEqual({
      kind: 'restore-phrase',
    });
  });

  it('испорченный конверт тоже ведёт к фразе', () => {
    // The password behind a damaged envelope was generated by the application, so the
    // password prompt cannot open it either: the phrase is the only way back, and the
    // keypad would be a screen that cannot succeed.
    expect(phaseAfterPinLookup(PROFILE, 'damaged', true)).toEqual({
      kind: 'restore-phrase',
    });
  });

  it('без поддержки PIN в сборке показывает пароль этого профиля', () => {
    expect(phaseAfterPinLookup(PROFILE, 'ready', false)).toEqual({
      kind: 'password',
      profile: PROFILE,
    });
  });
});

describe('pinProblem', () => {
  it('принимает PIN в допустимых границах', () => {
    expect(pinProblem('1234', 4, 12)).toBeNull();
    expect(pinProblem('123456789012', 4, 12)).toBeNull();
  });

  it('отвергает слишком короткий PIN', () => {
    // The keypad already stops at the maximum, so this is the failure a user can reach.
    expect(pinProblem('123', 4, 12)).toBe('The PIN is too short');
  });

  it('отвергает слишком длинный PIN', () => {
    expect(pinProblem('1234567890123', 4, 12)).toBe('The PIN is too long');
  });
});

describe('parseNetwork', () => {
  it('принимает обе известные сети', () => {
    expect(parseNetwork('mainnet')).toBe('mainnet');
    expect(parseNetwork('testnet')).toBe('testnet');
  });

  it('отвергает постороннее значение', () => {
    // The value becomes part of a filesystem path on the Rust side.
    expect(parseNetwork('../../etc')).toBeNull();
    expect(parseNetwork('')).toBeNull();
  });
});

describe('pairingMethods', () => {
  it('предлагает Wi-Fi и USB, QR пока выключен', () => {
    const methods = pairingMethods();
    expect(methods.find((m) => m.id === 'wifi')?.enabled).toBe(true);
    expect(methods.find((m) => m.id === 'usb')?.enabled).toBe(true);
    // `qr` has no implementation; it stays visible because the camera permission exists
    // for it, and a disabled row is honest about that.
    expect(methods.find((m) => m.id === 'qr')?.enabled).toBe(false);
  });
});
